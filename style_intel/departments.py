"""Department analysis: what a channel team would know about a reference video's sound, lined up with its picture.

Music (identified, where it starts in the track, edits/speed, key, ducking under the voice), every sound effect by family
(sub-bass boom, tonal ping, high tick, whoosh, riser) with the frames and words at that moment, voice pace and pauses, and
whether each sound family is tied to picture changes. Everything here is MEASURED or IDENTIFIED; the job and feeling of
each sound family are written by a reviewer from this evidence (INFERRED), never generated by this module.

The machine cannot hear: sounds are found from separated stems (Demucs) and their spectra.
"""
from __future__ import annotations

import io
import json
import math
import subprocess
import sys
import tempfile
from pathlib import Path

import cv2
import numpy as np
from scipy.stats import binomtest, kstest, rankdata

from .media import extract_audio, probe

SR = 22050
HOP = 256
DEFAULTS = {
    "boom_hz": 60, "boom_jump_db": 14.0, "boom_gap_sec": 0.5, "boom_floor_db": 25.0,
    "tone_band_hz": (600, 10000), "tone_db": 26.0, "tone_background_sec": 3.0, "ping_min_sec": 0.2,
    "whoosh_band_hz": (2000, 10000), "whoosh_rise_db": 12.0, "whoosh_flatness": 0.25, "whoosh_len_sec": (0.15, 1.2),
    "riser_slopes": (15, 20, 25, 30), "riser_window_sec": 0.6, "riser_db": 16.0,
    "event_gap_sec": 0.25, "sync_window_sec": (-0.2, 0.3), "sync_rank": 0.8,
    "shazam_window_sec": 15.0,
}
NOTE_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
# Krumhansl-Kessler key profiles
MAJOR = np.array([6.35, 2.23, 3.48, 2.33, 4.38, 4.09, 2.52, 5.19, 2.39, 3.66, 2.29, 2.88])
MINOR = np.array([6.33, 2.68, 3.52, 5.38, 2.60, 3.53, 2.54, 4.75, 3.98, 2.69, 3.34, 3.17])
SCALE = {"major": [0, 2, 4, 5, 7, 9, 11], "minor": [0, 2, 3, 5, 7, 8, 10]}


# ---------------------------------------------------------------- stems
def stems(video: Path, work: Path) -> dict[str, Path]:
    """Demucs 4-stem split (cached in work/stems). no_vocals = drums + bass + other."""
    import soundfile as sf
    out = work / "stems"
    names = ["vocals", "drums", "bass", "other"]
    if not all((out / f"{n}.wav").is_file() for n in names):
        out.mkdir(parents=True, exist_ok=True)
        wav = extract_audio(video, work / "audio.wav", sr=44100)
        with tempfile.TemporaryDirectory() as td:
            subprocess.run([sys.executable, "-m", "demucs", "-n", "htdemucs", "-o", td, str(wav)], check=True, capture_output=True)
            src = next(Path(td).glob("htdemucs/*"))
            for n in names:
                (src / f"{n}.wav").replace(out / f"{n}.wav")
    if not (out / "no_vocals.wav").is_file():
        parts = [sf.read(out / f"{n}.wav") for n in ("drums", "bass", "other")]
        sf.write(out / "no_vocals.wav", sum(p[0] for p in parts), parts[0][1])
    return {n: out / f"{n}.wav" for n in names + ["no_vocals"]}


def load(path: Path) -> np.ndarray:
    import librosa
    y, _ = librosa.load(str(path), sr=SR, mono=True)
    return y


def spectrum(y: np.ndarray):
    import librosa
    S = np.abs(librosa.stft(y, n_fft=2048, hop_length=HOP))
    f = librosa.fft_frequencies(sr=SR, n_fft=2048)
    t = librosa.frames_to_time(np.arange(S.shape[1]), sr=SR, hop_length=HOP)
    return S, librosa.amplitude_to_db(S, ref=np.max(S) + 1e-12), f, t


# ---------------------------------------------------------------- sound effects
def _onsets(x: np.ndarray, t: np.ndarray, thr: float, gap: float) -> list[int]:
    """Frame indices where x crosses thr upward (re-armed 3 dB below), merged within gap seconds."""
    out, armed = [], True
    for i, v in enumerate(x):
        if armed and v > thr:
            if not out or t[i] - t[out[-1]] > gap:
                out.append(i)
            armed = False
        elif v < thr - 3:
            armed = True
    return out


def note_of(hz: float) -> dict:
    midi = 69 + 12 * math.log2(hz / 440.0)
    n = int(round(midi))
    return {"hz": round(hz, 1), "note": f"{NOTE_NAMES[n % 12]}{n // 12 - 1}", "pitch_class": n % 12, "cents": round((midi - n) * 100)}


def sound_events(no_vocals: np.ndarray, cfg: dict = DEFAULTS) -> list[dict]:
    """Every sound-effect candidate in the voice-free layer, by family, with the numbers that found it."""
    import librosa
    S, db, f, t = spectrum(no_vocals)
    ev: list[dict] = []

    sub = 10 * np.log10(np.sum(S[f < cfg["boom_hz"]] ** 2, 0) + 1e-12)
    jump = sub - np.median(sub)  # against the whole video: hits a second apart would lift a local median (41e2e6b7)
    jump[sub < sub.max() - cfg["boom_floor_db"]] = -99  # a jump out of near-silence is not a hit
    for i in _onsets(jump, t, cfg["boom_jump_db"], cfg["boom_gap_sec"]):
        ev.append({"t": round(float(t[i]), 2), "family": "boom", "evidence": {"sub_bass_above_usual_db": round(float(jump[i:i + 8].max()), 1)}})

    ev += tones(db, f, t, cfg)

    lo, hi = cfg["whoosh_band_hz"]
    sel = (f >= lo) & (f < hi)
    env = librosa.amplitude_to_db(S[sel].sum(0) + 1e-9)
    flat = librosa.feature.spectral_flatness(S=S[sel])[0]
    smooth = np.convolve(env, np.ones(5) / 5, mode="same")
    base = np.array([np.median(smooth[max(0, k - 200):k + 1]) for k in range(len(smooth))])
    w_lo, w_hi = cfg["whoosh_len_sec"]
    k = 0
    while k < len(smooth):
        if smooth[k] - base[k] > cfg["whoosh_rise_db"] and flat[k] > cfg["whoosh_flatness"]:
            s = k
            while s > 0 and smooth[s - 1] < smooth[s] and smooth[s - 1] - base[k] > 3:
                s -= 1
            e = k
            while e < len(smooth) - 1 and smooth[e] - base[k] > 3:
                e += 1
            if w_lo <= t[e] - t[s] <= w_hi and s < k:
                ev.append({"t": round(float(t[s]), 2), "family": "whoosh", "evidence": {
                    "rise_db": round(float(smooth[k] - base[k]), 1), "length_sec": round(float(t[e] - t[s]), 2), "flatness": round(float(flat[k]), 2)}})
            k = e + 1
        else:
            k += 1

    ev += risers(db, f, t, cfg)
    ev.sort(key=lambda e: e["t"])
    return ev


def tones(db: np.ndarray, f: np.ndarray, t: np.ndarray, cfg: dict = DEFAULTS) -> list[dict]:
    """Tonal sounds: pings ring (>= ping_min_sec), ticks/clicks are short. Found as a narrow line far louder than that same frequency
    usually is over the surrounding seconds. Music notes that recur raise their own background and are not counted;
    comparing with neighbouring frequencies instead lets a music bed's every note through (MEASURED on 41e2e6b7)."""
    from scipy.ndimage import median_filter, percentile_filter
    lo, hi = cfg["tone_band_hz"]
    sel = (f >= lo) & (f < hi)
    B, fb = db[sel], f[sel]
    span = int(cfg["tone_background_sec"] * SR / HOP)
    above = B - percentile_filter(B, 75, size=(1, 2 * span + 1), mode="nearest")  # a note present a quarter of the time is bed
    narrow = above - median_filter(above, size=(41, 1), mode="nearest")
    score = np.minimum(above, narrow + 8)
    best, k = score.max(0), score.argmax(0)
    out = []
    for i in _onsets(best, t, cfg["tone_db"], cfg["event_gap_sec"]):
        j = i
        while j + 1 < len(best) and score[k[i], j + 1] > cfg["tone_db"] - 10:
            j += 1
        hz, length = float(fb[k[i]]), float(t[j] - t[i])
        out.append({"t": round(float(t[i]), 2), "family": "ping" if length >= cfg["ping_min_sec"] else "tick", "pitch": note_of(hz),
                    "evidence": {"above_usual_level_db": round(float(best[i]), 1), "length_sec": round(length, 2)}})
    return out


def sound_groups(events: list[dict]) -> list[dict]:
    """Tonal events at the same pitch (within a semitone) used 3+ times: probably one sound file reused."""
    groups: dict[tuple, list[float]] = {}
    for e in events:
        if "pitch" in e:
            midi = round(69 + 12 * math.log2(e["pitch"]["hz"] / 440.0))
            groups.setdefault((e["family"], midi), []).append(e["t"])
    return [{"family": fam, "note": f"{NOTE_NAMES[m % 12]}{m // 12 - 1}", "times": ts}
            for (fam, m), ts in sorted(groups.items(), key=lambda kv: -len(kv[1])) if len(ts) >= 3]


def risers(db: np.ndarray, f: np.ndarray, t: np.ndarray, cfg: dict = DEFAULTS) -> list[dict]:
    """Upward sweeps (risers): on a semitone grid of how far each pitch is above its usual level, average along rising
    lines (riser_slopes semitones/s over riser_window_sec) and subtract the best flat or falling line through the same
    spot, so broadband hits and sustained notes do not count. Tracing the loudest frequency misses a riser under music
    (MEASURED on 41e2e6b7: the upload riser at 32.6-33.6 s is never the loudest line)."""
    from scipy.ndimage import median_filter
    hz = 200 * 2 ** (np.arange(64) / 12)  # 200 Hz .. 8 kHz
    G = db[np.minimum(np.searchsorted(f, hz), len(f) - 1)]
    span = int(cfg["tone_background_sec"] * SR / HOP)
    A = np.clip(G - median_filter(G, size=(1, 2 * span + 1), mode="nearest"), -10, 40)
    L, n = int(cfg["riser_window_sec"] * SR / HOP), A.shape[1]
    if n <= L:
        return []

    def line(slope: float) -> np.ndarray:
        step, acc = slope * HOP / SR, np.zeros((64, n - L))
        for k in range(L):
            dp = int(round(k * step))
            sh = np.full((64, n - L), -10.0)
            if dp >= 0:
                sh[:64 - dp] = A[dp:, k:k + n - L]
            else:
                sh[-dp:] = A[:64 + dp, k:k + n - L]
            acc += sh
        return acc / L

    other = np.maximum(line(0), line(-cfg["riser_slopes"][-1]))
    best, arg = np.full(n - L, -99.0), np.zeros((n - L, 2), int)
    for slope in cfg["riser_slopes"]:
        up = line(slope)
        side = np.maximum(np.roll(up, 4, axis=0), np.roll(up, -4, axis=0))  # a tone sweep is narrow; a noise band is not
        c = np.minimum(up - other, up - side)
        m = c.max(0)
        better = m > best
        best[better], arg[better, 0], arg[better, 1] = m[better], c.argmax(0)[better], slope
    out: list[dict] = []
    for j in np.argsort(best)[::-1]:
        if best[j] < cfg["riser_db"]:
            break
        if all(abs(t[j] - e["t"]) > 1.0 for e in out):
            p, slope = arg[j]
            out.append({"t": round(float(t[j]), 2), "family": "riser", "evidence": {
                "from_hz": int(hz[p]), "semitones_per_sec": int(slope), "line_above_flat_db": round(float(best[j]), 1)}})
    return out


# ---------------------------------------------------------------- music
def identify_music(no_vocals: Path, duration: float, work: Path, cfg: dict = DEFAULTS) -> dict:
    """Shazam on 15 s windows of the voice-free layer (needs network; uv + Python 3.12 + shazamio).

    The offset of each match against video time tells where the track starts, whether it was edited (offsets jump)
    and whether it was sped up (slope != 1)."""
    win = cfg["shazam_window_sec"]
    starts = list(np.arange(0, max(duration - win, 0) + 1e-6, win)) or [0.0]
    script = work / "_shazam.py"
    script.write_text(
        "import asyncio, json, sys\nfrom shazamio import Shazam\n"
        "async def main():\n    s = Shazam(); out = []\n"
        "    for f in sys.argv[1:]:\n"
        "        try:\n            r = await s.recognize(f)\n        except Exception as e:\n            out.append({'error': str(e)}); continue\n"
        "        t = r.get('track') or {}; m = (r.get('matches') or [{}])[0]\n"
        "        out.append({'title': t.get('title'), 'artist': t.get('subtitle'), 'offset': m.get('offset')})\n"
        "    print(json.dumps(out))\nasyncio.run(main())\n", encoding="utf-8")
    clips = []
    for k, s in enumerate(starts):
        c = work / f"_music_{k}.wav"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", f"{s:.2f}", "-t", f"{win:.2f}", "-i", str(no_vocals), "-ac", "1", str(c)], check=True)
        clips.append(c)
    try:
        r = subprocess.run(["uv", "run", "--python", "3.12", "--with", "shazamio", "python", str(script), *map(str, clips)],
                           capture_output=True, text=True, timeout=600)
        res = json.loads(r.stdout.strip().splitlines()[-1])
    except Exception as e:  # offline, uv missing, timeout
        return {"status": "not_measured", "reason": f"music identification failed: {e}"}
    finally:
        for c in clips:
            c.unlink(missing_ok=True)
        script.unlink(missing_ok=True)
    windows = [{"video_sec": round(float(s), 2), **m} for s, m in zip(starts, res)]
    hits = [w for w in windows if w.get("title") and w.get("offset") is not None]
    if not hits:
        return {"status": "measured", "identified": False, "windows": windows}
    title = max({(w["title"], w["artist"]) for w in hits}, key=lambda k: sum((w["title"], w["artist"]) == k for w in hits))
    same = [w for w in hits if (w["title"], w["artist"]) == title]
    starts_in_track = [w["offset"] - w["video_sec"] for w in same]
    speed = None
    if len(same) >= 2:
        speed = round((same[-1]["offset"] - same[0]["offset"]) / (same[-1]["video_sec"] - same[0]["video_sec"]), 3)
    return {"status": "measured", "identified": True, "title": title[0], "artist": title[1],
            "track_time_at_video_start_sec": round(float(np.median(starts_in_track)), 2),
            "continuous": bool(np.ptp(starts_in_track) < 1.0) if len(same) >= 2 else None,
            "speed": speed, "windows_matched": f"{len(same)}/{len(windows)}", "windows": windows}


def music_key(music: np.ndarray) -> dict:
    """Key by Krumhansl-Kessler correlation of the mean chroma (INFERRED; short or atonal music is unreliable)."""
    import librosa
    chroma = librosa.feature.chroma_cqt(y=music, sr=SR).mean(1)
    scores = []
    for tonic in range(12):
        for mode, prof in (("major", MAJOR), ("minor", MINOR)):
            scores.append((float(np.corrcoef(chroma, np.roll(prof, tonic))[0, 1]), tonic, mode))
    scores.sort(reverse=True)
    best, second = scores[0], scores[1]
    return {"key": f"{NOTE_NAMES[best[1]]} {best[2]}", "tonic": best[1], "mode": best[2], "correlation": round(best[0], 3),
            "runner_up": f"{NOTE_NAMES[second[1]]} {second[2]} ({second[0]:.3f})"}


def tuning(pings: list[dict], key: dict) -> dict:
    """Are the pings' pitches in the music's key? Compared with chance (7 of 12 pitch classes)."""
    if not pings:
        return {"status": "no pings"}
    scale = {(key["tonic"] + s) % 12 for s in SCALE[key["mode"]]}
    inside = [p for p in pings if p["pitch"]["pitch_class"] in scale]
    test = binomtest(len(inside), len(pings), 7 / 12, alternative="greater")
    return {"in_key": f"{len(inside)}/{len(pings)}", "chance": "7/12", "p_value": round(float(test.pvalue), 3),
            "notes": sorted({p["pitch"]["note"] for p in pings})}


def ducking(music: np.ndarray, words: list[tuple]) -> dict:
    """Music level while the voice speaks vs in the gaps (positive = music dips under the voice)."""
    step = int(0.1 * SR)
    T = np.arange(0, len(music) / SR - 0.1, 0.1)
    lvl = np.array([20 * np.log10(np.sqrt(np.mean(music[int(x * SR):int(x * SR) + step] ** 2)) + 1e-9) for x in T])
    speech = np.array([any(s - 0.05 <= x <= e + 0.05 for s, e, _ in words) for x in T])
    if speech.sum() < 5 or (~speech).sum() < 5:
        return {"status": "not enough speech and gaps to compare"}
    a, b = float(np.median(lvl[speech])), float(np.median(lvl[~speech]))
    curve = [{"from_sec": int(s), "music_db": round(float(np.median(lvl[(T >= s) & (T < s + 4)])), 1)} for s in range(0, int(T[-1]) + 1, 4)]
    return {"music_under_voice_db": round(a, 1), "music_in_gaps_db": round(b, 1), "dip_db": round(b - a, 1), "level_every_4s": curve}


# ---------------------------------------------------------------- voice
def voice(vocals: Path) -> tuple[list[tuple], dict]:
    from faster_whisper import WhisperModel
    model = WhisperModel("base", device="cpu", compute_type="int8")
    with tempfile.TemporaryDirectory() as td:
        wav = extract_audio(vocals, Path(td) / "v.wav", sr=16000)
        segs, _ = model.transcribe(str(wav), word_timestamps=True, vad_filter=True)
        words = [(round(w.start, 2), round(w.end, 2), w.word.strip()) for s in segs for w in s.words]
    if len(words) < 2:
        return words, {"has_speech": bool(words)}
    dur = words[-1][1] - words[0][0]
    pauses = [{"at_sec": words[i + 1][0], "length_sec": round(words[i + 1][0] - words[i][1], 2)}
              for i in range(len(words) - 1) if words[i + 1][0] - words[i][1] > 0.3]
    return words, {"has_speech": True, "words": len(words), "words_per_minute": round(60 * len(words) / dur),
                   "first_word_sec": words[0][0], "pauses_over_0_3s": pauses}


# ---------------------------------------------------------------- picture
def picture_change(video: Path, cfg: dict = DEFAULTS) -> tuple[np.ndarray, float]:
    """For every frame i: how different the picture is just after (i + 0.3 s) from just before (i - 0.2 s), as mean
    absolute grey difference at 48x27. A before/after comparison catches a headline or card arriving on a background
    that keeps moving; a frame-to-frame difference is dominated by that background (MEASURED on 41e2e6b7)."""
    cap = cv2.VideoCapture(str(video))
    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    grey = []
    while True:
        ok, fr = cap.read()
        if not ok:
            break
        grey.append(cv2.resize(cv2.cvtColor(fr, cv2.COLOR_BGR2GRAY), (48, 27), interpolation=cv2.INTER_AREA))
    cap.release()
    g = np.array(grey, dtype=np.int16)
    a, b = (int(round(x * fps)) for x in cfg["sync_window_sec"])
    n = len(g)
    change = np.array([np.abs(g[min(i + b, n - 1)] - g[max(i + a, 0)]).mean() for i in range(n)], dtype=np.float32)
    return change, fps


def sync(events: list[dict], change: np.ndarray, fps: float, cfg: dict = DEFAULTS) -> dict:
    """Rank each event's before/after picture change against every moment of the video (0..1; 0.5 = an ordinary moment).
    An event is marked on a picture change at rank >= sync_rank. Per family, a one-sided KS test asks whether its ranks
    sit higher than chance: a family that follows the picture is an effect laid to it; one that does not is likely music."""
    ranks = (rankdata(change) - 1) / max(len(change) - 1, 1)  # ties share a rank
    fam: dict[str, list[bool]] = {}
    for e in events:
        i = min(int(round(e["t"] * fps)), len(change) - 1)
        e["picture_change_rank"] = round(float(ranks[i]), 2)
        e["on_picture_change"] = bool(ranks[i] >= cfg["sync_rank"])
        fam.setdefault(e["family"], []).append(e["on_picture_change"])
    out = {}
    for k, v in fam.items():
        rk = [e["picture_change_rank"] for e in events if e["family"] == k]
        out[k] = {"events": len(v), "on_picture_change": sum(v), "median_rank": round(float(np.median(rk)), 2),
                  "p_value": round(float(kstest(rk, "uniform", alternative="less").pvalue), 4)}
    return out


def frames_at(video: Path, t: float, width: int = 150):
    from PIL import Image
    b = subprocess.run(["ffmpeg", "-v", "error", "-ss", f"{max(t, 0):.3f}", "-i", str(video), "-frames:v", "1",
                        "-vf", f"scale={width}:-1", "-f", "image2pipe", "-c:v", "png", "-"], capture_output=True).stdout
    return Image.open(io.BytesIO(b)) if b else None


def event_sheets(video: Path, events: list[dict], words: list[tuple], out: Path, per_page: int = 16) -> list[str]:
    """For every event: the frames just before, at and after it, the voice at that moment and the family/pitch."""
    from PIL import Image, ImageDraw, ImageFont
    try:
        font = ImageFont.truetype("arial.ttf", 15)
    except OSError:
        font = ImageFont.load_default()
    tiles = []
    for e in events:
        shots = [frames_at(video, e["t"] + d) for d in (-0.15, 0.05, 0.3)]
        shots = [s for s in shots if s is not None]
        if not shots:
            continue
        w, h = shots[0].size
        im = Image.new("RGB", (3 * (w + 2), h + 44), "black")
        d = ImageDraw.Draw(im)
        for i, s in enumerate(shots):
            im.paste(s, (i * (w + 2), 44))
        near = " ".join(x for s, en, x in words if s - 0.35 <= e["t"] <= en + 0.15)
        tag = e["family"].upper() + (f" {e['pitch']['note']}" if "pitch" in e else "")
        d.text((4, 2), f"{e['t']:5.2f}s {tag}", fill="yellow", font=font)
        d.text((4, 22), f"voice: {near}"[:60], fill="white", font=font)
        tiles.append(im)
    names = []
    for p in range(0, len(tiles), per_page):
        page = tiles[p:p + per_page]
        cols = 4
        W, H = max(t.width for t in page), max(t.height for t in page)
        sheet = Image.new("RGB", (cols * W, ((len(page) + cols - 1) // cols) * H), "gray")
        for i, im in enumerate(page):
            sheet.paste(im, ((i % cols) * W, (i // cols) * H))
        name = f"events_{p // per_page + 1:02d}.png"
        sheet.save(out / name)
        names.append(name)
    return names


# ---------------------------------------------------------------- run + report
def analyze(video: Path, out: Path, identify: bool = True, sheets: bool = True, cfg: dict = DEFAULTS) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    info = probe(video)
    st = stems(video, out)
    nv, music = load(st["no_vocals"]), load(st["other"]) + load(st["bass"])
    words, vstats = voice(st["vocals"])
    events = sound_events(nv, cfg)
    change, fps = picture_change(video, cfg)
    families = sync(events, change, fps, cfg)
    key = music_key(music)
    pings = [e for e in events if e["family"] == "ping"]
    result = {
        "source": {"file": video.name, "duration_sec": info.get("duration_sec"), "fps": fps},
        "music": {"identification": identify_music(st["no_vocals"], info.get("duration_sec") or len(nv) / SR, out, cfg) if identify
                  else {"status": "not_measured", "reason": "skipped"},
                  "key": key, "ducking": ducking(music, words)},
        "voice": vstats,
        "sound_families": families,
        "sound_groups": sound_groups(events),
        "ping_tuning": tuning(pings, key),
        "events": events,
        "not_measured": {
            "feeling": "the job and emotion of each sound family are INFERRED by a reviewer from this evidence",
            "sound_identity": "families come from spectrum shape; what made a sound (a real object, a library file) is not known",
            "music_vs_effect": "a ping or boom can be part of the music; a family that follows picture changes is more likely an effect",
        },
    }
    (out / "words.json").write_text(json.dumps(words), encoding="utf-8")
    if sheets:
        result["sheets"] = event_sheets(video, events, words, out)
    (out / "departments.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    (out / "departments.md").write_text(report(result), encoding="utf-8")
    return result


JOB_PROMPT = "_job (INFERRED, write after looking at the sheets): what this sound does for the viewer_"


def report(r: dict) -> str:
    m, v = r["music"], r["voice"]
    mid = m["identification"]
    if mid.get("identified"):
        cont = {True: "plays continuously", False: "is edited (offsets jump)", None: "continuity unknown (one window)"}[mid["continuous"]]
        ms = (f"**{mid['title']}** by {mid['artist']} (IDENTIFIED, {mid['windows_matched']} windows): enters at "
              f"{mid['track_time_at_video_start_sec']:.1f} s of the track, {cont}, speed {mid['speed']}.")
    else:
        ms = f"not identified ({mid.get('reason') or 'no match'})."
    k, dk = m["key"], m["ducking"]
    lines = [f"# Department analysis: {r['source']['file']}", "",
             "MEASURED / IDENTIFIED evidence. The machine cannot hear: sounds were separated (Demucs) and found from their spectra. "
             "The job and feeling of each sound family are for a reviewer to write (INFERRED).", "",
             "## Music", f"- Track: {ms}",
             f"- Key (INFERRED from chroma): {k['key']} (r={k['correlation']}; runner-up {k['runner_up']})."]
    if "dip_db" in dk:
        lines.append(f"- Mix: music {dk['music_under_voice_db']} dB under the voice, {dk['music_in_gaps_db']} dB in the gaps (dips {dk['dip_db']} dB).")
    lines += ["", "## Voice"]
    if v.get("has_speech") and "words_per_minute" in v:
        lines.append(f"- {v['words']} words, {v['words_per_minute']} words/min, first word at {v['first_word_sec']} s.")
        lines.append(f"- Pauses over 0.3 s at: {', '.join(str(p['at_sec']) for p in v['pauses_over_0_3s']) or 'none'}.")
    else:
        lines.append("- No speech.")
    lines += ["", "## Sound effects by family", "",
              "Median rank: how big the picture change is at each sound, against every moment of the video (0.5 = chance). "
              "A family tied to the picture (small p) is an effect laid to it; one that is not is probably part of the music.", "",
              "| family | events | median rank | top-20% changes | p |", "|---|---|---|---|---|"]
    for fam, s in r["sound_families"].items():
        lines.append(f"| {fam} | {s['events']} | {s['median_rank']} | {s['on_picture_change']} | {s['p_value']} |")
    pt = r["ping_tuning"]
    if "in_key" in pt:
        lines.append(f"\nPing pitches in the music's key: {pt['in_key']} (chance {pt['chance']}, p={pt['p_value']}); notes {', '.join(pt['notes'])}.")
    if r.get("sound_groups"):
        lines += ["", "Same pitch used 3+ times (probably one sound file reused):"]
        lines += [f"- {g['family']} {g['note']}: {', '.join(f'{x:.2f}' for x in g['times'])} s" for g in r["sound_groups"]]
    for fam in r["sound_families"]:
        lines += ["", f"### {fam}", JOB_PROMPT]
        for e in (e for e in r["events"] if e["family"] == fam):
            pitch = f" {e['pitch']['note']} ({e['pitch']['hz']} Hz)" if "pitch" in e else ""
            mark = "picture change" if e["on_picture_change"] else "-"
            lines.append(f"- {e['t']:.2f} s{pitch} [{mark}] {json.dumps(e['evidence'])}")
    lines += ["", "## Not measured", *[f"- **{a}**: {b}" for a, b in r["not_measured"].items()]]
    if r.get("sheets"):
        lines += ["", "Review sheets (frames before/at/after each event, with the voice): " + ", ".join(r["sheets"])]
    return "\n".join(lines) + "\n"
